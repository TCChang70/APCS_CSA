public class OP1 {
    public static void main(String[] args) {
        int a=10;
        int b=3;

        System.out.println("加法: " + (a + b));
        System.out.println("減法: " + (a - b));
        System.out.println("乘法: " + (a * b));
        System.out.println("除法: " + (a / b));
        System.out.println("餘數: " + (a % b));
    }
}
