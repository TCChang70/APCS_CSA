"""
=============================================================================
P3. 帕斯卡三角形（初級）— 完整程式說明
=============================================================================

【問題回顧】
給定 N，輸出帕斯卡三角形第 0 列到第 N 列。
C(n, k) = C(n-1, k-1) + C(n-1, k)，邊界 C(n,0)=C(n,n)=1

【解題思維】
組合數 C(n, k) 的遞迴定義本身就是帕斯卡三角形的生成規則：
  - 基底：在最左邊 (k=0) 或最右邊 (k=n) 時，值為 1
  - 遞迴：內部格子等於左上 + 正上（即 C(n-1,k-1) + C(n-1,k)）

注意：樸素遞迴有大量重複計算（如 C(5,2) 和 C(5,3) 都會算 C(4,2)），
因此加入 memo dict 做記憶化（Memorization），將 O(2ⁿ) 降為 O(N²)。

=============================================================================
程式碼逐段說明
=============================================================================
"""

import sys
input = sys.stdin.readline


def C(n, k, memo=None):
    """
    遞迴計算組合數 C(n, k)，搭配 memoization 避免重複計算。

    參數：
      n, k : 組合數上下標
      memo : 記憶字典，預設為 None 時建立空字典

    遞迴三要素：
    1. 基底條件：k == 0 或 k == n → 回傳 1
    2. 遞迴關係：C(n, k) = C(n-1, k-1) + C(n-1, k)
    3. 收斂性：n 和 k 都往 0 或邊界縮小

    注意 memo 參數陷阱：
      不要用 def C(n, k, memo={})，因為可變預設參數會共用！
      應該在函式內建立 memo，或傳入 None 再初始化。
    """
    if memo is None:           # 第一次呼叫時建立新 memo
        memo = {}
    if k == 0 or k == n:       # 基底條件：邊緣為 1
        return 1
    key = (n, k)               # 用 tuple 當字典鍵
    if key in memo:            # 記憶化：查表
        return memo[key]
                               # 遞迴計算並存入 memo
    memo[key] = C(n - 1, k - 1, memo) + C(n - 1, k, memo)
    return memo[key]


def main():
    """
    main() 流程：
    1. 讀取 N
    2. 對 n = 0..N 的每一列：
       a. 對 k = 0..n 計算 C(n, k)
       b. 將結果轉字串，以空白連接輸出
    """
    N = int(input())           # 讀取 N
    for n in range(N + 1):     # 第 0 列到第 N 列
        row = [str(C(n, k)) for k in range(n + 1)]
        print(' '.join(row))   # 以空白間隔


if __name__ == '__main__':
    main()
"""
=============================================================================
時間複雜度：O(N²)
  每對 (n, k) 只計算一次並存入 memo，總共約 N²/2 個狀態。

空間複雜度：O(N²)
  memo 字典儲存所有計算過的 (n, k) 組合。

手動追蹤（N=3）：
  C(0,0)=1
  C(1,0)=1  C(1,1)=1
  C(2,0)=1  C(2,1)=C(1,0)+C(1,1)=2  C(2,2)=1
  C(3,0)=1  C(3,1)=C(2,0)+C(2,1)=3  C(3,2)=C(2,1)+C(2,2)=3  C(3,3)=1

APCS 考點：
  1. 遞迴 + 記憶化（Memoization）的經典組合
  2. Python 可變物件當預設參數的陷阱
  3. 組合數遞迴定義與帕斯卡三角形的關係
=============================================================================
"""
