"""
【APCS 遞迴練習題 1】最大公因數與最小公倍數（初級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
給定兩個正整數 a 和 b，請使用遞迴實作輾轉相除法（Euclidean algorithm）
計算它們的最大公因數（GCD）和最小公倍數（LCM）。

LCM(a, b) = a × b ÷ GCD(a, b)

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
第一行：一個正整數 N，表示有 N 組測試資料
接下來 N 行：每行兩個正整數 a 和 b（1 ≤ a, b ≤ 10⁹）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
對每組測試資料輸出一行「GCD LCM」

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
3
12 18
7 13
24 36

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
6 36
1 91
12 72

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
輾轉相除法（Euclidean algorithm）：
  gcd(a, b) = a (若 b == 0)
  gcd(a, b) = gcd(b, a % b) (若 b > 0)
每次遞迴 b 會縮小（因 a % b < b），必然收斂到 b == 0。
時間複雜度 O(log min(a, b))
"""

import sys
input = sys.stdin.readline


def gcd(a, b):
    if b == 0:
        return a
    return gcd(b, a % b)


def main():
    N = int(input())
    for _ in range(N):
        a, b = map(int, input().split())
        g = gcd(a, b)
        l = a // g * b
        print(g, l)


if __name__ == '__main__':
    main()
