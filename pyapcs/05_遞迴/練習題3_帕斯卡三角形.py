"""
【APCS 遞迴練習題 3】帕斯卡三角形（初級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
帕斯卡三角形（Pascal's Triangle）是一個由組合數 C(n, k) 構成的三角形，
其中每一列的數字由上方的兩個數字相加得到：
  C(n, k) = C(n-1, k-1) + C(n-1, k)
  邊界條件：C(n, 0) = C(n, n) = 1

請使用遞迴實作：給定 N，輸出帕斯卡三角形的第 0 列到第 N 列。
N ≤ 30（注意：遞迴深度不深，但組合數可能很大，請使用 Python 大整數）

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
一個正整數 N（0 ≤ N ≤ 30）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
輸出 N+1 列，第 i 列有 i+1 個數字，以空白間隔

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
5

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1
1 1
1 2 1
1 3 3 1
1 4 6 4 1
1 5 10 10 5 1

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
遞迴實現組合數 C(n, k)：
  C(n, 0) = C(n, n) = 1（基底條件）
  C(n, k) = C(n-1, k-1) + C(n-1, k)（遞迴關係）

注意：未經記憶化的遞迴會重複計算，但 N ≤ 30 時仍在可接受範圍。
若要優化可加入 memoization。
"""

import sys
input = sys.stdin.readline


def C(n, k, memo=None):
    if memo is None:
        memo = {}
    if k == 0 or k == n:
        return 1
    key = (n, k)
    if key in memo:
        return memo[key]
    memo[key] = C(n - 1, k - 1, memo) + C(n - 1, k, memo)
    return memo[key]


def main():
    N = int(input())
    for n in range(N + 1):
        row = [str(C(n, k)) for k in range(n + 1)]
        print(' '.join(row))


if __name__ == '__main__':
    main()
