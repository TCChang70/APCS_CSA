"""
=============================================================================
P2. 數位根（初級）— 完整程式說明
=============================================================================

【問題回顧】
數位根是將整數的每一位數相加，直到結果為個位數為止。
例如：98765 → 9+8+7+6+5=35 → 3+5=8 → 數位根為 8

【解題思維】
遞迴策略：
  1. 基底條件：n < 10 → 回傳 n（已是個位數）
  2. 遞迴關係：先計算各位數和 s，再對 s 呼叫 digital_root(s)

關鍵操作：
  - n % 10：取出最右邊的數字
  - n // 10：去掉最右邊的數字
  兩者搭配可以逐一取出所有位數。

=============================================================================
程式碼逐段說明
=============================================================================
"""

import sys
input = sys.stdin.readline


def digital_root(n):
    """
    遞迴計算數位根。

    第一階段：計算 n 的各位數總和 s
      while n > 0:          # 當 n 還有位數時
          s += n % 10       # 取出個位數加到 s
          n //= 10          # 去掉個位數，十位變個位⋯

    第二階段：判斷是否需繼續遞迴
      if s < 10: return s   # 基底條件：已是個位數
      return digital_root(s) # 否則對 s 繼續化簡

    範例追蹤 digital_root(98765)：
      n=98765 → s=9+8+7+6+5=35 → digital_root(35)
      n=35 → s=3+5=8 → 8<10 → return 8
    """
    s = 0                    # 初始化位數和
    while n > 0:             # 逐一取出每一位數
        s += n % 10          # 取出個位數，累加到 s
        n //= 10             # 去掉個位數
    if s < 10:               # 基底條件：和為個位數
        return s
    return digital_root(s)   # 遞迴：對和繼續化簡


def main():
    """
    main() 流程：
    1. 讀取 N（測資筆數）
    2. 對每個數字 x：
       a. 呼叫 digital_root(x)
       b. 輸出結果
    """
    N = int(input())          # 讀取測資筆數
    for _ in range(N):        # 逐筆處理
        x = int(input())      # 讀入正整數（可達 10¹⁸，但 Python 可處理）
        print(digital_root(x)) # 輸出數位根


if __name__ == '__main__':
    main()
