"""
【APCS 遞迴練習題 2】數位根（初級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
數位根（Digital Root）是將一個正整數的所有位數相加，
若結果為個位數則停止，否則重複此過程直到得到個位數。

例如：
  98765 → 9+8+7+6+5 = 35
  35 → 3+5 = 8
  數位根為 8

請使用遞迴實作。

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
第一行：一個正整數 N，表示有 N 個數字
接下來 N 行：每行一個正整數 x（1 ≤ x ≤ 10¹⁸）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
對每個 x 輸出一行，表示它的數位根

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
4
98765
0
9999
12345

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
8
0
9
6

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
遞迴數位和：
  digital_root(n) = n（若 n < 10）
  digital_root(n) = digital_root(n//10 + n%10)（遞迴化簡）
或者使用數學公式：digital_root = 1 + (n-1) % 9（n > 0 時）
但本題要求遞迴實作，故使用第一種方式。
"""

import sys
input = sys.stdin.readline


def digital_root(n):
    s = 0
    while n > 0:
        s += n % 10
        n //= 10
    if s < 10:
        return s
    return digital_root(s)


def main():
    N = int(input())
    for _ in range(N):
        x = int(input())
        print(digital_root(x))


if __name__ == '__main__':
    main()
