"""
【APCS 中級】蒐集寶石
試題來源：程式實作 2024 年 10 月

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
M×N 的二維場地，-1 = 牆壁，其他值 = 格子的寶石數（0 或正整數）。
機器人從 (r, c) 開始，初始方向朝東（右），初始得分 = 0。

行動規則（循環執行）：
  1. 若當前格子無寶石（= 0）→ 停止。
  2. 得分 += 當前格子寶石數，取得 1 顆（格子寶石 -1）。
  3. 若得分是 K 的倍數 → 向右轉（順時針 90 度）。
  4. 若正前方是牆壁或界外 → 向右轉；持續直到前方可走。
  5. 進入前方格子，回到步驟 1。

輸出機器人最終蒐集到的寶石總數。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
直接模擬機器人行動：
  - 方向以 (dr, dc) 表示：東(0,1)、南(1,0)、西(0,-1)、北(-1,0)
  - 向右轉 = 方向陣列索引 +1（取模 4）
  - 步驟 4 的連續右轉：最多轉 4 次（轉一圈回到原方向表示被圍）

題目保證機器人最終一定會停下來，故直接模擬即可。
"""

import sys
input = sys.stdin.readline


def main():
    M, N, K, r, c = map(int, input().split())

    # 讀入場地（M 行，每行 N 個值）
    grid = []
    for _ in range(M):
        row = list(map(int, input().split()))
        grid.append(row)

    # ── 方向定義（順序：東、南、西、北） ─────────────────────
    # 向右轉（順時針）= 方向索引 + 1（mod 4）
    DIRS = [(0, 1), (1, 0), (0, -1), (-1, 0)]   # 東、南、西、北
    dir_idx = 0   # 初始朝東（索引 0）

    # ── 初始狀態 ─────────────────────────────────────────────
    score = 0     # 目前得分
    gems = 0      # 蒐集到的寶石數
    row, col = r, c

    # ── 模擬主迴圈 ───────────────────────────────────────────
    while True:
        # 步驟 1：若當前格子無寶石則停止
        if grid[row][col] == 0:
            break

        # 步驟 2：得分 += 寶石數，取得 1 顆，格子寶石減 1
        score += grid[row][col]
        gems += 1
        grid[row][col] -= 1

        # 步驟 3：若得分是 K 的倍數，向右轉
        if score % K == 0:
            dir_idx = (dir_idx + 1) % 4

        # 步驟 4：若前方是牆壁或界外，持續向右轉
        # 最多轉 4 次（若轉一圈後仍無路可走，題目保證不會發生）
        for _ in range(4):
            dr, dc = DIRS[dir_idx]
            nr, nc = row + dr, col + dc
            # 檢查是否在場地內且不是牆壁（-1）
            if 0 <= nr < M and 0 <= nc < N and grid[nr][nc] != -1:
                break   # 前方可走，離開迴圈
            # 前方不可走 → 向右轉
            dir_idx = (dir_idx + 1) % 4

        # 步驟 5：進入前方格子
        dr, dc = DIRS[dir_idx]
        row, col = row + dr, col + dc

    # 輸出蒐集到的寶石總數
    print(gems)


if __name__ == '__main__':
    main()
