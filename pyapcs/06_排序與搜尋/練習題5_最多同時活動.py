"""
【APCS 排序搜尋練習題 5】最多同時進行的活動（中級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
給定 N 個活動，每個活動有開始時間 S 與結束時間 T（S < T）。
若兩個活動的時間區間有交集（端點相接不算，即 T1 = S2 時不重疊），
則稱它們同時進行。

請找出所有時間點中，最多有多少個活動同時進行。

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
第一行：正整數 N（1 ≤ N ≤ 10⁵）
接下來 N 行：每行兩個整數 S 和 T（0 ≤ S < T ≤ 10⁹）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
一個整數，表示最大同時進行的活動數量

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
5
1 4
3 5
2 7
6 8
4 6

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
3

說明：時間點 4~5 之間有活動 (1,4)、(3,5)、(2,7) 三個同時進行。
(4,6) 的開始時間 4 與 (1,4) 的結束時間 4 相接，不視為重疊。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
掃描線（Sweep Line）：
1. 每個活動拆成兩個事件：(S, +1) 和 (T, -1)
2. 對事件排序，時間相同時結束事件 (-1) 優先（端點不重疊）
3. 掃描事件，維護當前活動數量，記錄最大值
時間複雜度 O(N log N)
"""

import sys
input = sys.stdin.readline


def main():
    N = int(input())
    events = []
    for _ in range(N):
        S, T = map(int, input().split())
        events.append((S, 1))
        events.append((T, -1))

    events.sort(key=lambda x: (x[0], x[1]))

    cur = 0
    ans = 0
    for _, typ in events:
        cur += typ
        if cur > ans:
            ans = cur

    print(ans)


if __name__ == '__main__':
    main()
