"""
【APCS 排序搜尋練習題 4】區間合併與覆蓋長度（中級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
給定 N 個區間 [L, R]（L < R，皆為整數），每個區間代表一條
水管覆蓋的範圍。水管之間可能重疊，請計算所有水管實際覆蓋的
總長度（重疊部分只算一次）。

例如：水管 [1,5] 和 [3,7] 覆蓋了 [1,7]，長度為 6。

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
第一行：正整數 N（1 ≤ N ≤ 10⁵）
接下來 N 行：每行兩個整數 L 和 R（0 ≤ L < R ≤ 10⁹）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
一個整數，表示覆蓋總長度

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
4
1 5
3 7
2 4
8 10

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
8

說明：[1,7] 長度 6 + [8,10] 長度 2 = 8

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1. 依 L 排序所有區間
2. 掃描合併：維護當前覆蓋範圍 curL, curR
   - 若新區間的 L ≤ curR，表示重疊 → 延伸 curR
   - 否則代表斷開 → 計算 curR - curL 並開始新區間
3. 最後加上最後一段的長度
時間複雜度 O(N log N)
"""

import sys
input = sys.stdin.readline


def main():
    N = int(input())
    intervals = []
    for _ in range(N):
        L, R = map(int, input().split())
        intervals.append((L, R))

    intervals.sort(key=lambda x: x[0])

    total = 0
    curL, curR = intervals[0]

    for L, R in intervals[1:]:
        if L <= curR:
            curR = max(curR, R)
        else:
            total += curR - curL
            curL, curR = L, R

    total += curR - curL
    print(total)


if __name__ == '__main__':
    main()
