"""
【APCS 排序搜尋練習題 2】數字頻率統計與排序（初級）

問題描述
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
給定一個長度為 N 的整數陣列（N ≤ 10000，元素範圍 0~100），
請統計每個數字出現的頻率，並按以下規則排序輸出：

1. 頻率高者在前
2. 頻率相同時，數字小者在前面

輸入格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
第一行：正整數 N
第二行：N 個整數（以空白間隔）

輸出格式
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
每行輸出「數字 頻率」，依規則排序。

範例輸入
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
10
3 1 4 1 5 3 1 4 3 3

範例輸出
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
3 4
1 3
4 2
5 1

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
演算法說明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1. 元素範圍 0~100，可用計數排序（Counting Sort）統計頻率
2. 過濾出出現次數 > 0 的數字
3. 依 (頻率 DESC, 數字 ASC) 排序輸出
時間複雜度 O(N + K log K)，K ≤ 101
"""

import sys
input = sys.stdin.readline


def main():
    N = int(input())
    arr = list(map(int, input().split()))

    freq = [0] * 101
    for v in arr:
        freq[v] += 1

    entries = [(v, freq[v]) for v in range(101) if freq[v] > 0]
    entries.sort(key=lambda x: (-x[1], x[0]))

    for v, cnt in entries:
        print(v, cnt)


if __name__ == '__main__':
    main()
